SELECT

season_id,
team,
sum(number_of_games) as games_played,
SUM(HOME_WINS) + SUM(AWAY_WINS) AS wins,
sum(number_of_games) - SUM(HOME_WINS) - SUM(AWAY_WINS) - SUM(LOSSES) as  draws,
SUM(LOSSES) as losses,
SUM(GOALS_FOR) AS GOALS_FOR,
SUM(GOAL_AGAINST) AS GOALS_AGAINST,
SUM(GOALS_FOR) - SUM(GOAL_AGAINST) AS goaldifference,
SUM(HOME_POINTS) + SUM(AWAY_POINTS) as points,
SUM(HOME_WINS) AS home_wins,
SUM(AWAY_WINS) AS away_wins,
SUM(home_goals) AS HOME_GOALS,
SUM(away_goals) AS AWAY_GOALS,
SUM(clean_sheets) AS CLEAN_SHEETS,
SUM(GOALS_FOR) AS GOALS_SCORED,
SUM(HOME_POINTS) AS HOME_POINTS,
SUM(AWAY_POINTS) AS AWAY_POINTS,
SUM(HOME_POINTS) + SUM(AWAY_POINTS) AS TOTAL_POINTS
FROM(

select 
season_id,
home_team_id as team,
count(home_team_id) as number_of_games,
SUM(HOME_GOALS) AS GOALS_FOR,
SUM(AWAY_GOALS) AS GOAL_AGAINST,
SUM(HOME_GOALS) AS HOME_GOALS,
0 AS AWAY_GOALS,
SUM(CASE WHEN ISNULL(AWAY_GOALS,0) = 0 THEN 1 ELSE 0 END) AS CLEAN_SHEETS,
SUM(CASE 
		WHEN FULL_TIME_RESULT = 'H' THEN 1
		ELSE 0 END
	)  AS HOME_WINS,
0 AS AWAY_WINS,
SUM(CASE 
		WHEN FULL_TIME_RESULT = 'A' THEN 1
		ELSE 0 END
	)  AS LOSSES,
SUM(CASE 
		WHEN FULL_TIME_RESULT = 'H' THEN 3
		WHEN FULL_TIME_RESULT = 'D' THEN 1
		ELSE 0 END
	)  AS HOME_POINTS,
0 AS AWAY_POINTS
from fact_match
GROUP BY season_id,
home_team_id

UNION ALL

select 
season_id,
away_team_id as team,
count(away_team_id) as number_of_games,
SUM(away_goals) AS GOALS_FOR,
SUM(HOME_GOALS) AS GOAL_AGAINST,
0 AS HOME_GOALS,
SUM(AWAY_GOALS) AS AWAY_GOALS,
SUM(CASE WHEN ISNULL(home_goals,0) = 0 THEN 1 ELSE 0 END) AS CLEAN_SHEETS,
0 AS HOME_WINS,
SUM(CASE 
		WHEN FULL_TIME_RESULT = 'A' THEN 1
		ELSE 0 END
	)  AS AWAY_WINS,
SUM(CASE 
		WHEN FULL_TIME_RESULT = 'H' THEN 1
		ELSE 0 END
	)  AS LOSSES,
0 AS HOME_POINTS,
SUM(CASE 
		WHEN FULL_TIME_RESULT = 'A' THEN 3
		WHEN FULL_TIME_RESULT = 'D' THEN 1
		ELSE 0 END
	)  AS AWAY_POINTS
from fact_match
GROUP BY season_id,
away_team_id
)CALC

GROUP BY season_id,team





